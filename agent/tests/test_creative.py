@pytest.mark.parametrize(
    "change, reason",
    [
        ({"category": "plumbers"}, 'the category "plumbers" is not one of the trades'),
        ({"category": None}, 'has no "category"'),
        ({"file": ""}, 'has no "file"'),
        ({"alt": ""}, 'has no "alt"'),
        ({"alt": "   "}, 'has no "alt"'),
        ({"licence": None}, 'has no "licence"'),
        ({"source": 12}, 'has no "source"'),
        ({"services": "Invisalign"}, '"services" is not a list of names'),
        ({"services": ["Invisalign", 3]}, '"services" is not a list of names'),
    ],
)
def test_an_entry_missing_a_field_or_naming_another_trade_is_skipped(tmp_path, monkeypatch, caplog, change, reason):
    creative_picture(tmp_path / "dentists/1.jpg")
    only(tmp_path, monkeypatch, {**GOOD, **change})
    with caplog.at_level(logging.WARNING, logger=LOGGER):
        assert creative.manifest() == []
    refused(caplog, "", reason)


def test_an_entry_without_a_field_at_all_or_not_an_object_is_skipped(tmp_path, monkeypatch, caplog):
    creative_picture(tmp_path / "dentists/1.jpg")
    no_alt = {k: v for k, v in GOOD.items() if k != "alt"}
    only(tmp_path, monkeypatch, no_alt, "dentists/1.jpg", None, GOOD)
    with caplog.at_level(logging.WARNING, logger=LOGGER):
        assert creative.manifest() == [GOOD]
    refused(caplog, "", 'has no "alt"')
    refused(caplog, "", "is not an object")


@pytest.mark.parametrize(
    "content",
    [None, "{ not json", "[]", '{"entries": "none"}', '{"entries": {"a": 1}}', ""],
    ids=["no file", "bad json", "a list", "entries a string", "entries an object", "empty"],
)
def test_a_manifest_that_cannot_be_read_is_an_empty_set_and_a_warning_not_a_crash(
    tmp_path, monkeypatch, caplog, content
):
    monkeypatch.setattr(creative, "ROOT", tmp_path)
    if content is not None:
        (tmp_path / "manifest.json").write_text(content, encoding="utf-8")
    with caplog.at_level(logging.WARNING, logger=LOGGER):
        assert creative.manifest() == [] and creative.pick("dentists", None) is None
    assert any(r.name == LOGGER and "manifest.json" in r.getMessage() for r in caplog.records)


def test_the_reasons_are_for_the_operator_and_never_name_where_the_files_live(tmp_path, monkeypatch, caplog):
    creative_picture(tmp_path / "dentists/small.jpg", size=(100, 100))
