"""The licensed image set (M1 Task 3; `agent/channels/newsbreak/creative.py`): the manifest and its schema, the pick of
a picture by trade and service, and the pictures it refuses -- NewsBreak takes JPEG or PNG, at least 1200 x 627 pixels,
at most 5 MB. The set the tests use is generated (`agent/tests/fixtures.py`: `creative_set`, 1200 x 675 solid-colour
JPEGs): the real pictures are the founder's to add, and `manifest.json` ships with the schema and no entries."""

from __future__ import annotations

import json
import logging
import typing

import pytest

from agent import models
from agent.channels.newsbreak import creative
from agent.tests.fixtures import creative_picture, creative_set

LOGGER = "agent.channels.newsbreak.creative"
GOOD = {
    "file": "dentists/1.jpg",
    "category": "dentists",
    "services": [],
    "licence": "Test picture: no licence needed",
    "source": "generated by agent/tests/fixtures.py",
    "alt": "A solid blue test picture",
}


@pytest.fixture
def images(tmp_path, monkeypatch):
    """The generated set, in place of the shipped one."""
    root = creative_set(tmp_path / "creative")
    monkeypatch.setattr(creative, "ROOT", root)
    return root


def write_manifest(root, entries) -> None:
    (root / "manifest.json").write_text(json.dumps({"entries": entries}), encoding="utf-8")


def only(root, monkeypatch, entry, *others) -> None:
    """A set whose manifest lists `entry` (the picture it names is the test's to make) and then `others`."""
    monkeypatch.setattr(creative, "ROOT", root)
    write_manifest(root, [entry, *others])


# ---------------------------------------------------------------- the shipped manifest


def test_the_shipped_manifest_documents_its_fields_and_every_entry_in_it_is_one_creative_takes():
    """The schema is in the file for the founder who adds the pictures; whatever is listed must pass the checks, so a
    picture that is too small or not licensed in the manifest fails here, in CI, and not as a skipped ad."""
    raw = json.loads((creative.ROOT / "manifest.json").read_text(encoding="utf-8"))
    assert set(raw) == {"schema", "entries"}
    assert tuple(raw["schema"]) == creative.FIELDS
    assert all(isinstance(text, str) and text for text in raw["schema"].values())
    assert isinstance(raw["entries"], list)
    for entry in raw["entries"]:
        assert creative.problem(entry) is None, entry
    assert creative.manifest() == raw["entries"]  # nothing the founder lists is skipped


def test_the_trade_categories_are_the_benchmarks():
    """A category in the manifest is one a plan can have: `models.Category`'s eleven."""
    assert creative.CATEGORIES == typing.get_args(models.Category)


